export const localeNames = { 'zh-CN': '简体中文', en: 'English' };

export function isLocale(value) {
  return typeof value === 'string' && Object.hasOwn(localeNames, value);
}

export function preferredLocale(languages) {
  for (const language of languages) {
    const base = language.toLowerCase().split('-')[0];
    if (base === 'zh') return 'zh-CN';
    if (base === 'en') return 'en';
  }
  return 'zh-CN';
}

export function savedLocale(cookie) {
  return /(?:^|;\s*)excalink_locale=(zh-CN|en)(?:;|$)/.exec(cookie || '')?.[1];
}

